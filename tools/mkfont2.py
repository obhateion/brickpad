#!/usr/bin/env python3
"""Bakes DejaVu Sans Mono (regular and bold) at the sizes of the UI v2 mockups into src/fontv2.h: natural spacing,
ASCII 32..126 plus three marks: 127 '>' as U+203A, 1 as U+25B6 (play), 2 as U+25A0 (stop). 4-bit alpha.
Usage: python3 tools/mkfont2.py > src/fontv2.h   (DejaVu: Bitstream Vera licence, free to embed)."""
from PIL import Image, ImageDraw, ImageFont

D = '/usr/share/fonts/dejavu/'
FONTS = [('FT_S', 'DejaVuSansMono.ttf', 17), ('FT_M', 'DejaVuSansMono.ttf', 20), ('FT_MB', 'DejaVuSansMono-Bold.ttf', 20),
         ('FT_LB', 'DejaVuSansMono-Bold.ttf', 23), ('FT_XB', 'DejaVuSansMono-Bold.ttf', 30)]
CH = [chr(c) for c in range(32, 127)] + ['›', '▶', '■']   # glyph index = byte - 32; 127, 1, 2 map to the last three

out = ['// Generated by tools/mkfont2.py from DejaVu Sans Mono (Bitstream Vera licence). Do not edit.',
       '// Each font: glyph cell w x h, the cap top at y = top, 98 glyphs (ASCII 32..126, then > play stop), 4-bit alpha.',
       '#pragma once', 'enum { %s, FT_N };' % ', '.join(f[0] for f in FONTS)]
heads = []
for name, ttf, size in FONTS:
    f = ImageFont.truetype(D + ttf, size)
    w = int(round(f.getlength('M'))); asc, desc = f.getmetrics(); h = asc + desc
    cap = -f.getbbox('H', anchor='ls')[1]; top = asc - cap
    data = bytearray()
    for ch in CH:
        im = Image.new('L', (w, h), 0)
        ImageDraw.Draw(im).text((0, asc), ch, font=f, fill=255, anchor='ls')
        px = list(im.getdata()) + [0]
        for i in range(0, w * h, 2):
            data.append((px[i] >> 4) << 4 | px[i + 1] >> 4)
    per = (w * h + 1) // 2
    out.append('static const unsigned char %s_px[%d] = {' % (name.lower(), len(data)))
    for i in range(0, len(data), 40):
        out.append('    ' + ','.join(str(b) for b in data[i:i + 40]) + ',')
    out.append('};')
    heads.append('    {%d, %d, %d, %d, %s_px},' % (w, h, top, per, name.lower()))
out.append('typedef struct { int w, h, top, per; const unsigned char *px; } FontV2;')
out.append('static const FontV2 fv2[FT_N] = {')
out += heads
out.append('};')
print('\n'.join(out))
