#!/usr/bin/env python3
"""Bakes DejaVu Sans Mono into src/fontmono.h: ASCII 32..126 in the cells of the old 8x8 font at scales 1, 2 and 3
(8, 16, 24 px), 4-bit alpha, two pixels a byte. Usage: python3 tools/mkfont.py [TTF] > src/fontmono.h
DejaVu fonts: Bitstream Vera licence (free to embed and redistribute, see https://dejavu-fonts.github.io/License.html)."""
import sys
from PIL import Image, ImageDraw, ImageFont

TTF = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/dejavu/DejaVuSansMono-Bold.ttf'
SIZES = {1: 10, 2: 17, 3: 26}          # scale -> font size: caps fill about 0.75 of the cell

out = ['// Generated by tools/mkfont.py from DejaVu Sans Mono Bold (Bitstream Vera licence). Do not edit.',
       '// fm_glyph[s]: scale s (1..3), 95 glyphs (ASCII 32..126) of 8s x 8s pixels, 4-bit alpha, high nibble first.',
       '#pragma once']
for sc, size in SIZES.items():
    cell = 8 * sc
    f = ImageFont.truetype(TTF, size)
    adv = f.getlength('M')
    cap = f.getbbox('H', anchor='ls')
    cap_h = -cap[1]
    base = (cell - cap_h) // 2 + cap_h  # caps centred in the cell
    data = bytearray()
    for ch in range(32, 127):
        im = Image.new('L', (cell, cell), 0)
        ImageDraw.Draw(im).text(((cell - adv) / 2, base), chr(ch), font=f, fill=255, anchor='ls')
        px = list(im.getdata())
        for i in range(0, len(px), 2):
            data.append((px[i] >> 4) << 4 | px[i + 1] >> 4)
    out.append('static const unsigned char fm_s%d[%d] = {' % (sc, len(data)))
    for i in range(0, len(data), 32):
        out.append('    ' + ','.join(str(b) for b in data[i:i + 32]) + ',')
    out.append('};')
out.append('static const unsigned char *const fm_glyph[4] = {0, fm_s1, fm_s2, fm_s3};')
print('\n'.join(out))
