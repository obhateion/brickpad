static const char *par_hint(int p) {
    if (p > 0 && p < P_TYPE) return hint_sm[p];
    if (p == P_SRC) return "THE SAMPLE THE GRAINS COME FROM: EDIT BROWSES";
    if (p == P_SX + SX_FIN) return "THE SOUND COMES IN OVER THIS TIME INSTEAD OF AT ONCE";
    if (p == P_SX + SX_FOUT) return "THE SOUND FADES OVER THIS TIME BEFORE ITS END, AND WHEN A STEP OR NOTE CUTS IT";
    if (p == P_SX + SX_XFADE) return "A SLICE OR NOTE PLAYS ON THIS LONG PAST ITS END WHILE THE NEXT ONE FADES IN: NO CLICKS BETWEEN SLICES";
    if (p == P_NORM) return "BRINGS A QUIET SAMPLE UP: PEAK BY ITS LOUDEST POINT, LOUD BY ITS AVERAGE LEVEL";
    if (p >= P_SY && p < P_SY + SP_N) return hint_sy[p - P_SY];
    if (p >= P_AC && p < P_AC + AP_N) return hint_ac[p - P_AC];
    if (p >= P_CL && p < P_CL + CP_N) return hint_cl[p - P_CL];
    if (p >= P_CX && p < P_CX + CX_N) return hint_cx[p - P_CX];
    if (p >= P_AX && p < P_AX + AX_N) return hint_ax[p - P_AX];
    if (p >= P_GX && p < P_GX + GX_N) return hint_gx[p - P_GX];
    if (p >= P_PT && p < P_PT + 16) return "AN OUTPUT: EDIT TAKES A CABLE FROM HERE, EDIT ON AN INPUT PLUGS IT";
    if (p >= P_PT + 16 && p < P_PT + 32) return "AN INPUT: A CABLE HERE REPLACES WHAT FEEDS IT NORMALLY. OPT+EDIT PULLS IT";
    if (p == P_SLWAY) return "EQUAL: SAME-SIZE PARTS. TRANSIENTS: A CUT AT EVERY HIT. BY HAND: YOUR OWN POINTS";
    return NULL;
}
